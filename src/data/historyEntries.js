export const YEARS = YEARS_ASCENDING.slice()
  .reverse()
  .map((year) => ({ ...year, items: year.items.slice().reverse() }))

function buildShows() {
  const shows = {}

  YEARS_ASCENDING.forEach((year) => {
    year.items.forEach((item) => {
      if (!shows[item.showId]) {
        shows[item.showId] = { title: item.title, runs: [] }
      }

      shows[item.showId].runs.push({
        id: item.id,
        year: `20${year.yearBottom}`,
        role: item.caption,
        details: item.description.split('\n'),
      })
    })
  })

  return shows
}

export const SHOWS = buildShows()

export const HIDDEN_DETAIL_SHOW_IDS = new Set([
  'arirang-gyeongseong-26',
  'lion-king',
  'singing-in-the-rain',
  'gentlemans-guide',
])

export function getShow(showId) {
  if (HIDDEN_DETAIL_SHOW_IDS.has(showId)) return null
  return SHOWS[showId] ?? null
}
